"""Hand a finished clip to Nuke or After Effects.

Why this exists
  CorridorKey 2.0 is used inside compositing apps: you key a plate, then drop the result on a new background.
  This app already does the keying; what is left is getting the result *into* the comp quickly. These two
  helpers write a small script next to the results that does the setup for you:

    * Nuke:          a .nk file. Open it, or use File > Insert Comp Nodes to paste it into your own script.
                     It contains only Read nodes (+ a Premult after the Cutout), no multi-input nodes, so it
                     can never connect the wrong way round - you wire it into your own Merge.
    * After Effects: a .jsx script. File > Scripts > Run Script File... imports the results into a folder and
                     builds a comp (the Cutout as-is, or FG with the Matte as a luma track matte).

  Frame alignment: results of a partial run (Frame Limit) are placed on the timeline at the input frame they
  belong to, so they line up with the original footage.

  These scripts are generated from the documented formats of both apps but were NOT run inside Nuke or After
  Effects while building this app. Qt-free.
"""
from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from .model import Clip, discover_outputs, processed_range

LABELS = {"cutout": "CK_Cutout", "fg": "CK_FG", "alpha": "CK_Matte", "checker": "CK_Comp"}
ORDER = ("cutout", "fg", "alpha", "checker")
APP = "CorridorKey 2.0"


@dataclass
class OutputItem:
    key: str
    path: str                 # video file, or EXR sequence pattern with %0Nd
    sequence: bool
    first: int                # first / last frame number *in the files* (sequences) or 1 / count (video)
    last: int
    sample: str               # a real file (first frame) - used by After Effects, which wants a real name


def _fwd(p: str) -> str:
    return str(p).replace("\\", "/")


def _seq_info(folder: Path) -> Optional[tuple[str, int, int, str]]:
    rx = re.compile(r"^(.*?)(\d+)\.exr$", re.I)
    hits = []
    for f in folder.iterdir():
        m = rx.match(f.name)
        if m:
            hits.append((int(m.group(2)), len(m.group(2)), m.group(1), f.name))
    if not hits:
        return None
    hits.sort()
    first, width, prefix, first_name = hits[0]
    return f"{prefix}%0{width}d.exr", first, hits[-1][0], first_name


def collect_outputs(clip: Clip, out_dir: str) -> list[OutputItem]:
    found = discover_outputs(out_dir, clip.name, prefer=clip.settings.output_format)
    _start, n = processed_range(clip.frames, clip.kind, clip.settings)
    items: list[OutputItem] = []
    for key in ORDER:
        p = found.get(key)
        if not p:
            continue
        if os.path.isdir(p):
            info = _seq_info(Path(p))
            if info is None:
                continue
            pattern, first, last, first_name = info
            items.append(OutputItem(key, _fwd(os.path.join(p, pattern)), True, first, last,
                                    _fwd(os.path.join(p, first_name))))
        else:
            items.append(OutputItem(key, _fwd(p), False, 1, max(1, n), _fwd(p)))
    return items


def _timeline_start(clip: Clip) -> int:
    """Timeline frame (1-based) where the first result frame belongs."""
    return int(clip.ran_start) + 1


def _q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# --------------------------------------------------------------------------------------------- Nuke
def nuke_script(clip: Clip, out_dir: str) -> str:
    items = collect_outputs(clip, out_dir)
    if not items:
        raise ValueError("There are no finished results for this clip yet. Run inference first.")
    t0 = _timeline_start(clip)
    last_tl = max(clip.frames, t0 + max(i.last - i.first for i in items))
    w, h = (clip.width or 1920), (clip.height or 1080)
    lines = [
        f"#! generated by {APP} - Read nodes for the finished CorridorKey results",
        "version 13.0 v1",
        "Root {",
        " inputs 0",
        f" name {_q(_fwd(os.path.join(out_dir, clip.name + '_CorridorKey.nk')))}",
        " first_frame 1",
        f" last_frame {last_tl}",
        f" fps {clip.fps:g}",
        f" format {_q(f'{w} {h} 0 0 {w} {h} 1 CorridorKey')}",
        "}",
    ]
    x = 0
    for it in items:
        label = LABELS[it.key]
        lines += ["Read {", " inputs 0",
                  f" file {_q(it.path)}",
                  f" first {it.first}", f" last {it.last}",
                  f" origfirst {it.first}", f" origlast {it.last}"]
        if t0 != it.first:
            lines += [' frame_mode "start at"', f" frame {t0}"]
        lines += [f" name {label}", f" xpos {x}", " ypos 0", "}"]
        if it.key == "cutout":
            lines += ["Premult {", " name CK_Premult", f" xpos {x}", " ypos 90", "}"]
        x += 160
    notes = ["CorridorKey 2.0 results.",
             "CK_Cutout -> CK_Premult: connect CK_Premult to the A input of a Merge (over) on your background.",
             "CK_FG + CK_Matte: use ShuffleCopy (red from CK_Matte into alpha of CK_FG), then Premult.",
             "Results of a partial run sit at the input frame they were made from."]
    lines += ["StickyNote {", " inputs 0", " name CK_Note", f" label {_q(chr(10).join(notes))}",
              f" xpos {x}", " ypos 0", "}"]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------------------------- After Effects
_JSX = r"""// Generated by __APP__ - imports the finished CorridorKey results and builds a comp.
// Run it in After Effects with File > Scripts > Run Script File...
(function () {
    var DATA = __DATA__;
    var ITEM_NAMES = { cutout: "Cutout", fg: "FG", alpha: "Matte", checker: "Comp" };
    var missing = [];
    app.beginUndoGroup("__APP__ import");
    try {
        var proj = app.project ? app.project : app.newProject();
        var folder = proj.items.addFolder("CorridorKey - " + DATA.name);
        var got = {};
        for (var i = 0; i < DATA.items.length; i++) {
            var it = DATA.items[i];
            var f = new File(it.sample);
            if (!f.exists) { missing.push(it.sample); continue; }
            var io = new ImportOptions(f);
            if (it.sequence) { io.sequence = true; io.forceAlphabetical = false; }
            var footage = proj.importFile(io);
            footage.name = DATA.name + " " + ITEM_NAMES[it.key];
            footage.parentFolder = folder;
            got[it.key] = footage;
        }
        if (!got.cutout && !got.fg) {
            throw new Error("No cutout or FG results were found next to this script.");
        }
        var comp = proj.items.addComp("CorridorKey - " + DATA.name, DATA.width, DATA.height, 1.0,
                                      DATA.frames / DATA.fps, DATA.fps);
        comp.parentFolder = folder;
        var offset = DATA.offsetFrames / DATA.fps;      // partial runs sit at the input frame they came from
        if (got.cutout) {
            var cut = comp.layers.add(got.cutout);
            cut.startTime = offset;
            cut.name = "CorridorKey Cutout";
        } else {
            var fill = comp.layers.add(got.fg);
            fill.startTime = offset;
            fill.name = "CorridorKey FG";
            if (got.alpha) {
                var matte = comp.layers.add(got.alpha);   // goes on top of the fill layer
                matte.startTime = offset;
                matte.name = "CorridorKey Matte";
                if (typeof fill.setTrackMatte === "function") {
                    fill.setTrackMatte(matte, TrackMatteType.LUMA);
                } else {
                    fill.trackMatteType = TrackMatteType.LUMA;
                }
                matte.enabled = false;
            }
        }
        comp.openInViewer();
    } catch (e) {
        alert("__APP__ import stopped:\n" + e.toString());
    }
    app.endUndoGroup();
    if (missing.length) {
        alert("These files could not be found and were skipped:\n" + missing.join("\n"));
    }
})();
"""


def aftereffects_script(clip: Clip, out_dir: str) -> str:
    items = collect_outputs(clip, out_dir)
    if not items:
        raise ValueError("There are no finished results for this clip yet. Run inference first.")
    data = {
        "name": clip.name,
        "width": int(clip.width or 1920), "height": int(clip.height or 1080),
        "fps": float(clip.fps or 24.0), "frames": int(max(clip.frames, 1)),
        "offsetFrames": int(clip.ran_start),
        "items": [{"key": i.key, "sequence": i.sequence, "sample": i.sample} for i in items],
    }
    return _JSX.replace("__APP__", APP).replace("__DATA__", json.dumps(data, indent=8, ensure_ascii=True))


# --------------------------------------------------------------------------------------------- writing
KINDS = {
    "nuke": ("Nuke", ".nk", nuke_script),
    "ae": ("After Effects", ".jsx", aftereffects_script),
}


def write_export(kind: str, clip: Clip, out_dir: str, dest_dir: str = "") -> str:
    if kind not in KINDS:
        raise ValueError(f"Unknown export target: {kind}")
    _label, ext, fn = KINDS[kind]
    text = fn(clip, out_dir)
    dest = Path(dest_dir or out_dir)
    dest.mkdir(parents=True, exist_ok=True)
    path = dest / f"{clip.name}_CorridorKey{ext}"
    path.write_text(text, encoding="utf-8", newline="\n")
    return str(path)
